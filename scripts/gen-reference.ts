/**
 * Generates docs/reference/configuration.md: the configuration catalog of every plugin, from the
 * plugin's own `Config` schema (the one place each option is defined). `--check` fails when the
 * checked-in catalog is out of date (CI), so the reference cannot drift from the code.
 *
 * Without `--check` it also refreshes scripts/schema-snapshot.json, the record schemas' contracts
 * that `check:schemas` compares against; a schema changed in place keeps its old entry, so the
 * check keeps failing until the change is versioned (scripts/check-schemas.ts).
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { SNAPSHOT, writeSnapshot } from './check-schemas.ts'

/** The part of a Schemastery schema the generators read. */
export interface Schema {
  type: string
  meta?: { default?: unknown; description?: string | Record<string, string>; required?: boolean; min?: number; max?: number; role?: string }
  dict?: Record<string, Schema>
  inner?: Schema
  list?: Schema[]
  value?: unknown
}

const root = fileURLToPath(new URL('..', import.meta.url))
const OUT = join(root, 'docs', 'reference', 'configuration.md')

/** A schema as a short type expression. */
export function typeOf(schema: Schema): string {
  switch (schema.type) {
    case 'const': return JSON.stringify(schema.value)
    case 'union': return (schema.list ?? []).map(typeOf).join(' \\| ')
    case 'array': return `${schema.inner ? wrap(typeOf(schema.inner)) : 'unknown'}[]`
    case 'dict': return `Record<string, ${schema.inner ? typeOf(schema.inner) : 'unknown'}>`
    case 'object': return 'object'
    case 'natural': return 'natural number'
    case 'any': return 'any'
    default: return schema.type
  }
}

const wrap = (t: string): string => (t.includes(' \\| ') ? `(${t})` : t)

const describe = (schema: Schema): string => {
  const d = schema.meta?.description
  // A table cell: a backslash is escaped too, or one before a `|` would leave the pipe a cell break.
  return (typeof d === 'string' ? d : d?.en ?? '').replace(/[\\|]/g, '\\$&').replace(/\n/g, ' ')
}

/**
 * A default as a code span in a table cell. Only `|` is escaped: JSON writes a backslash only as
 * half of an escape pair, so a `|` is never left after an odd run of them, and inside a code span
 * an escaped backslash would show twice.
 */
const show = (value: unknown): string => (value === undefined ? '' : `\`${JSON.stringify(value)}\``.replace(/\|/g, '\\|'))

/** One row per option, nested objects flattened as dotted keys. */
export function rows(schema: Schema, prefix = ''): string[] {
  const out: string[] = []
  for (const [key, child] of Object.entries(schema.dict ?? {})) {
    const path = `${prefix}${key}`
    const bound = child.meta?.min !== undefined || child.meta?.max !== undefined ? ` (${child.meta.min ?? ''}…${child.meta.max ?? ''})` : ''
    out.push(`| \`${path}\`${child.meta?.required ? ' (required)' : ''} | ${typeOf(child)}${bound} | ${show(child.meta?.default)} | ${describe(child)} |`)
    if (child.type === 'object') out.push(...rows(child, `${path}.`))
    if (child.type === 'array' && child.inner?.type === 'object') out.push(...rows(child.inner, `${path}[].`))
  }
  return out
}

/**
 * Each plugin's `Config` schema, by directory, read from its source entry (a `Config` export, or
 * the default export's); undefined for a plugin with none. The workspace resolves from source, by
 * the root tsconfig's paths, so nothing needs building first. `gen:manifests` reads it too.
 */
export async function pluginConfigs(): Promise<Map<string, Schema | undefined>> {
  const plugins = join(root, 'packages', 'plugins')
  const out = new Map<string, Schema | undefined>()
  for (const dir of readdirSync(plugins).sort()) {
    const mod = await import(pathToFileURL(join(plugins, dir, 'src', 'index.ts')).href) as { Config?: Schema; default?: { Config?: Schema } }
    out.set(dir, mod.Config ?? mod.default?.Config)
  }
  return out
}

export async function render(): Promise<string> {
  const sections: string[] = []
  const plugins = join(root, 'packages', 'plugins')
  for (const [dir, config] of await pluginConfigs()) {
    const pkg = JSON.parse(readFileSync(join(plugins, dir, 'package.json'), 'utf8')) as { name: string }
    const options = config?.dict && Object.keys(config.dict).length ? rows(config) : []
    sections.push(`## \`${dir}\`\n\n[${pkg.name}](../../packages/plugins/${dir}/README.md)\n\n${options.length
      ? `| Option | Type | Default | Description |\n|---|---|---|---|\n${options.join('\n')}`
      : 'No options.'}`)
  }
  return [
    '# Configuration catalog',
    '',
    '> Generated by `pnpm gen:reference` from each plugin\'s `Config` schema; do not edit by hand.',
    '> CI fails when it is out of date. Values are set per profile in `cordis.patch.yml` rows',
    '> (deployment-varying values are validated `Config` fields, never code).',
    '',
    ...sections.flatMap((s) => [s, '']),
  ].join('\n')
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const text = await render()
  if (process.argv.includes('--check')) {
    const current = readFileSync(OUT, 'utf8')
    if (current !== text) {
      console.error('docs/reference/configuration.md is out of date: run `pnpm gen:reference`')
      process.exit(1)
    }
    console.log('reference: up to date')
  } else {
    writeFileSync(OUT, text)
    console.log(`wrote ${OUT}`)
    writeSnapshot(join(root, 'schemas'))
    console.log(`wrote ${SNAPSHOT}`)
  }
  process.exit(0)
}
